import type { SetSummary } from "../contract";

/**
 * Fixture set catalogue: real set numbers, names, years, themes and official
 * piece counts, each with a hand-built inventory whose quantities sum to that
 * piece count.
 *
 * The spread is deliberate. It covers a Technic set with no bulk wall material,
 * Classic boxes that can build everything, an Architecture set that is almost
 * all plate, and a small Creator set of specialised shapes that cannot build
 * anything at all — the inventory that exercises the empty-results path.
 *
 * `imgUrl` is null throughout: the client renders set identity typographically
 * rather than depending on a remote image host.
 */
export type MockLot = readonly [partNum: string, colorId: number, quantity: number];

export type MockSet = {
  summary: SetSummary;
  lots: readonly MockLot[];
};

const THEMES = {
  technic: { id: 1, name: "Technic" },
  classic: { id: 52, name: "Classic" },
  architecture: { id: 252, name: "Architecture" },
  creator: { id: 22, name: "Creator 3-in-1" },
  city: { id: 50, name: "City" },
  icons: { id: 721, name: "Icons" },
} as const;

type ThemeKey = keyof typeof THEMES;

function set(
  setNum: string,
  name: string,
  year: number,
  theme: ThemeKey,
  numParts: number,
  lots: readonly MockLot[],
): MockSet {
  return {
    summary: {
      setNum,
      name,
      year,
      themeId: THEMES[theme].id,
      themeName: THEMES[theme].name,
      numParts,
      imgUrl: null,
    },
    lots,
  };
}

