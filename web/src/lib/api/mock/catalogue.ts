export const SET_BY_NUM: ReadonlyMap<string, MockSet> = new Map(
  SETS.map((entry) => [entry.summary.setNum, entry]),
);

/**
 * Canonicalise what a user typed. CONTRACT.md requires a bare `42151` to
 * resolve to `42151-1`; trailing whitespace and case are also forgiven.
 */
export function canonicaliseSetNum(raw: string): string | null {
  const trimmed = raw.trim().toLowerCase();
  if (!trimmed) return null;
  if (SET_BY_NUM.has(trimmed)) return trimmed;
  const withVersion = `${trimmed}-1`;
  if (SET_BY_NUM.has(withVersion)) return withVersion;
  return null;
}
